#!/usr/bin/env node
/**
 * Renders the application's security headers for the documents nginx serves.
 *
 * ── Why this exists ──
 *
 * In production nginx serves `dist/` itself: the SPA page, its assets and the
 * uploaded pictures never pass through Express. helmet's Content-Security-Policy,
 * HSTS and the rest were therefore applied only to API responses — JSON, which a
 * CSP does not protect — and the page itself, the one response the policy exists
 * for, was served with none. Observed on the live site on 2026-09-13.
 *
 * Writing the headers into nginx by hand would create a second copy of a policy
 * that already has a careful, commented source, and the two would drift. So the
 * source stays `server/securityHeaders.js`, and this script asks helmet itself —
 * the same middleware Express runs — what it would send, then writes those
 * headers as nginx directives. `--check` fails if the committed file differs.
 *
 * The one deliberate difference, Referrer-Policy, is explained beside
 * `DOCUMENT_REFERRER_POLICY`.
 *
 * Usage:
 *   node bin/nginx-security-headers.mjs           write the snippet
 *   node bin/nginx-security-headers.mjs --check   exit 1 if it is out of date
 */
import { createServer } from 'node:http';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import express from 'express';
import helmet from 'helmet';
import { HELMET_OPTIONS, DOCUMENT_REFERRER_POLICY } from '../server/securityHeaders.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const SNIPPET_PATH = path.join(ROOT, 'deploy', 'nginx', 'wevolunteers-security-headers.conf');

/**
 * The headers helmet sets that belong on a document. Named rather than "all of
 * them", so a future helmet default that does not suit a static page arrives as
 * a deliberate addition here instead of silently.
 */
export const DOCUMENT_HEADERS = [
  'content-security-policy',
  'strict-transport-security',
  'cross-origin-opener-policy',
  'cross-origin-resource-policy',
  'origin-agent-cluster',
  'x-content-type-options',
  'x-dns-prefetch-control',
  'x-download-options',
  'x-frame-options',
  'x-permitted-cross-domain-policies',
  'x-xss-protection',
];

/** Canonical capitalisation, so the rendered file reads like the rest of the config. */
const DISPLAY = {
  'content-security-policy': 'Content-Security-Policy',
  'strict-transport-security': 'Strict-Transport-Security',
  'cross-origin-opener-policy': 'Cross-Origin-Opener-Policy',
  'cross-origin-resource-policy': 'Cross-Origin-Resource-Policy',
  'origin-agent-cluster': 'Origin-Agent-Cluster',
  'x-content-type-options': 'X-Content-Type-Options',
  'x-dns-prefetch-control': 'X-DNS-Prefetch-Control',
  'x-download-options': 'X-Download-Options',
  'x-frame-options': 'X-Frame-Options',
  'x-permitted-cross-domain-policies': 'X-Permitted-Cross-Domain-Policies',
  'x-xss-protection': 'X-XSS-Protection',
  'referrer-policy': 'Referrer-Policy',
};

/** Asks helmet, running exactly as Express runs it, for its headers. */
export async function helmetDocumentHeaders() {
  const app = express();
  app.use(helmet(HELMET_OPTIONS));
  app.get('/', (req, res) => res.type('html').send('<!doctype html>'));
  const server = createServer(app);
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  try {
    const res = await fetch(`http://127.0.0.1:${server.address().port}/`);
    const out = {};
    for (const name of DOCUMENT_HEADERS) {
      const value = res.headers.get(name);
      if (value === null) throw new Error(`helmet did not send ${name}; update DOCUMENT_HEADERS deliberately`);
      out[name] = value;
    }
    return out;
  } finally {
    await new Promise(resolve => server.close(resolve));
  }
}

export async function renderSnippet() {
  const headers = await helmetDocumentHeaders();
  const lines = [
    '# GENERATED by bin/nginx-security-headers.mjs from server/securityHeaders.js.',
    '# Do not edit by hand: change the source and re-run the script. CI fails when',
    '# this file and the source disagree (server/nginxSecurityHeaders.test.js).',
    '#',
    '# Included at server level and inside every location that declares its own',
    '# add_header, because nginx does not inherit add_header into such a location.',
    '',
  ];
  for (const name of DOCUMENT_HEADERS) {
    const value = headers[name];
    if (/["\\\n]/.test(value)) throw new Error(`${name} contains a character nginx would need escaped`);
    lines.push(`add_header ${DISPLAY[name]} "${value}" always;`);
  }
  lines.push(`add_header ${DISPLAY['referrer-policy']} "${DOCUMENT_REFERRER_POLICY}" always;`);
  return lines.join('\n') + '\n';
}

async function main() {
  const rendered = await renderSnippet();
  if (process.argv.includes('--check')) {
    const current = existsSync(SNIPPET_PATH) ? readFileSync(SNIPPET_PATH, 'utf8') : '';
    if (current !== rendered) {
      console.error(`${path.relative(ROOT, SNIPPET_PATH)} is out of date. Run: node bin/nginx-security-headers.mjs`);
      process.exit(1);
    }
    console.log('nginx security headers match server/securityHeaders.js');
    return;
  }
  writeFileSync(SNIPPET_PATH, rendered);
  console.log(`wrote ${path.relative(ROOT, SNIPPET_PATH)}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
