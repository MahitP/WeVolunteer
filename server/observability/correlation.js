/**
 * The join between a log record and the trace it belongs to.
 *
 * ── Why this is its own file ──
 *
 * `telemetry.js` is imported from the error path — `recordError` pulls it in, and
 * the express error handler calls it. Its import graph is therefore something to
 * keep small on purpose. Putting this function in `spans.js` would drag
 * `metrics.js` and `spanAttributes.js` behind it into every error, for the sake
 * of two hex strings.
 *
 * This module imports the OpenTelemetry **API** and nothing else. The API package
 * is a no-op by design when no SDK is registered, so importing it costs a
 * function call and works identically whether telemetry is on, off, or never
 * configured.
 *
 * ── Why the ids can ride in `id`-typed fields ──
 *
 * A trace id is 32 lower-case hex characters and a span id is 16. Both fit
 * `telemetry.js`'s `ID_SHAPE` (≤64, `[A-Za-z0-9_.:-]`), neither can match
 * `JWT_SHAPE`, and neither is derived from anything a user supplied — the ids are
 * generated by the SDK from a CSPRNG. So they satisfy the `id` contract exactly
 * as `requestId` and `fingerprint` do: opaque, bounded, this system's own.
 */
import { trace, context } from '@opentelemetry/api';

/** The all-zero trace id the API returns for an invalid span context. */
const INVALID_TRACE_ID = '00000000000000000000000000000000';

/**
 * `{ traceId, spanId }` for the active span, or `{}` when there is none.
 *
 * `{}` rather than nulls, so the caller can spread it into a record and have the
 * fields simply not appear — which is what should happen when tracing is off,
 * and is what `clean()` would do with them anyway.
 */
export function currentTraceIds() {
  try {
    const span = trace.getSpan(context.active());
    if (!span) return {};
    const ctx = span.spanContext();
    if (!ctx?.traceId || ctx.traceId === INVALID_TRACE_ID) return {};
    return { traceId: ctx.traceId, spanId: ctx.spanId };
  } catch {
    /* No SDK, a broken context manager, anything at all. A log record must not
       be lost because the correlation could not be worked out. */
    return {};
  }
}
